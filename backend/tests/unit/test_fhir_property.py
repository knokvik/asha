"""Property-based test for FHIR R4 Resource Serialisation Round-Trip (Property 17).

Specification:
- Requirement 36.2: ABDM FHIR R4 Bundles
- Requirement 52.6: Resource Serialization
- Property 17: For arbitrary valid FHIR R4 resources generated by the backend,
  assert `parse(serialise(resource)) == resource` with no field values lost, truncated, or type-coerced.
- Task 13.8
"""
