from models.db.models import ClinicalEncounter, ClinicalObservation, Member
from workers.abdm_sync import generate_abdm_bundle


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


@pytest.mark.asyncio
async def test_property_17_abdm_generated_bundles_round_trip(db_session: AsyncSession) -> None:
    """Property 17 Invariant on Backend ABDM bundles: parse(serialise(bundle)) == bundle."""
    now_ms = int(datetime.now(timezone.utc).timestamp() * 1000)
    member_id = f"mem_fhir_p17_{uuid.uuid4().hex[:8]}"

    member = Member(
        id=member_id,
        abha_id="14-9999-8888-7777",
        rch_id="RCH-P17-001",
        name="Sunita Devi Sharma",
        sex="F",
        dob_approx=now_ms - (28 * 365 * 86400 * 1000),
        created_at=now_ms,
        updated_at=now_ms,
    )
    db_session.add(member)

    # Seed clinical encounters
    enc_types = [
        ("IMMUNIZATION_DOSE", "immunization", "VACCINE_CODE", "PENTA_1"),
        ("ANC_VISIT", "maternal", "HAEMOGLOBIN", "11.5"),
        ("CBAC_SCREENING", "ncd", "BLOOD_PRESSURE_SYSTOLIC", "120"),
        ("TB_SCREENING", "tb", "SPUTUM_TEST", "NEGATIVE"),
    ]

    for enc_type, prog, obs_code, val in enc_types:
        enc = ClinicalEncounter(
            id=f"enc_p17_{uuid.uuid4().hex[:8]}",
            member_id=member_id,
            encounter_type=enc_type,
            program_code=prog,
            encounter_date=now_ms,
            created_at=now_ms,
            updated_at=now_ms,
        )
        db_session.add(enc)

        obs = ClinicalObservation(
            id=f"obs_p17_{uuid.uuid4().hex[:8]}",
            encounter_id=enc.id,
            observation_code=obs_code,
            value_text=val,
            observed_at=now_ms,
        )
        db_session.add(obs)

    await db_session.commit()

    consent = {
        "id": f"consent_p17_{uuid.uuid4().hex[:8]}",
        "status": "ACTIVE",
        "patient_id": member_id,
        "permitted_hi_types": ["WellnessRecord", "ImmunizationRecord", "OPConsultation", "DiagnosticReport"],
        "expires_at_ms": now_ms + 86400000,
    }

    # Test all 4 official ABDM Health Information types
    hi_types = ["WellnessRecord", "ImmunizationRecord", "OPConsultation", "DiagnosticReport"]

    for record_type in hi_types:
        bundle_dict = await generate_abdm_bundle(
            db=db_session,
            member_id=member_id,
            record_type=record_type,
            consent_artifact=consent,
        )

        # Parse from dictionary into Bundle model
        bundle_model = Bundle.parse_obj(bundle_dict)

        # Serialise to JSON string
        json_output = bundle_model.json()
        assert isinstance(json_output, str)
        assert len(json_output) > 200

        # Parse back from JSON string
        deserialized_bundle = Bundle.parse_raw(json_output)

        # Assert Property 17 Invariant: complete fidelity with no lost or truncated fields
        assert deserialized_bundle.dict() == bundle_model.dict(), (
            f"Property 17 Invariant violated for {record_type} bundle round-trip"
        )
        assert deserialized_bundle.id == bundle_model.id
        assert deserialized_bundle.type == "document"
        assert len(deserialized_bundle.entry) == len(bundle_model.entry)


def test_property_17_randomized_fhir_resources_round_trip() -> None:
    """Property 17 Invariant across 50 randomized FHIR R4 resources.

    Asserts parse(serialise(resource)) == resource for Patients, Observations,
    Immunizations, Encounters, DiagnosticReports, Compositions, and Bundles.
    """
    rnd = random.Random(42)

    genders = ["male", "female", "other", "unknown"]
    obs_codes = [
        ("8480-6", "Systolic blood pressure"),
        ("8462-4", "Diastolic blood pressure"),
        ("29463-7", "Body weight"),
        ("8302-2", "Body height"),
        ("718-7", "Hemoglobin [Mass/volume] in Blood"),
        ("2339-0", "Glucose [Mass/volume] in Blood"),
    ]
    vaccine_codes = ["BCG", "OPV-0", "PENTA-1", "ROTA-1", "PCV-1", "MR-1", "DPT-B1", "TD-10"]

    for trial in range(50):
        # 1. Randomized Patient
        patient_id = f"pat-{trial}-{rnd.randint(1000, 9999)}"
        gender = rnd.choice(genders)
        name = f"TestBeneficiary {trial}"
        birth_year = rnd.randint(1970, 2024)
        birth_date = f"{birth_year}-{rnd.randint(1, 12):02d}-{rnd.randint(1, 28):02d}"

        patient = Patient(
            id=patient_id,
            active=rnd.choice([True, False]),
            identifier=[
                Identifier(
                    system="https://healthid.ndhm.gov.in",
                    value=f"14-{rnd.randint(1000, 9999)}-{rnd.randint(1000, 9999)}-{rnd.randint(1000, 9999)}",
                )
            ],
            name=[HumanName(text=name, family="Kumar", given=["Aarav", f"Mid{trial}"])],
            gender=gender,
            birthDate=birth_date,
        )

        p_json = patient.json()
        parsed_p = Patient.parse_raw(p_json)
        assert parsed_p.dict() == patient.dict(), f"Patient round-trip failed at trial {trial}"

        # 2. Randomized Observation
        loinc_code, loinc_display = rnd.choice(obs_codes)
        val_numeric = round(rnd.uniform(10.0, 200.0), 2)
        patient_ref = Reference(reference=f"Patient/{patient_id}", display=name)

        observation = Observation(
            id=f"obs-{trial}-{rnd.randint(1000, 9999)}",
            status=rnd.choice(["preliminary", "final", "amended"]),
            code=CodeableConcept(
                coding=[
                    Coding(
                        system="http://loinc.org",
                        code=loinc_code,
                        display=loinc_display,
                    )
                ],
                text=loinc_display,
            ),
            subject=patient_ref,
            valueQuantity=Quantity(
                value=val_numeric,
                unit="unit",
                system="http://unitsofmeasure.org",
            ),
            effectiveDateTime=_now_iso(),
        )

        obs_json = observation.json()
        parsed_obs = Observation.parse_raw(obs_json)
        assert parsed_obs.dict() == observation.dict(), f"Observation round-trip failed at trial {trial}"

        # 3. Randomized Immunization
        v_code = rnd.choice(vaccine_codes)
        lot_no = f"LOT-{rnd.randint(10000, 99999)}"

        immunization = Immunization(
            id=f"imm-{trial}-{rnd.randint(1000, 9999)}",
            status="completed",
            vaccineCode=CodeableConcept(
                coding=[
                    Coding(
                        system="http://snomed.info/sct",
                        code=str(rnd.randint(100000, 999999)),
                        display=v_code,
                    )
                ],
                text=v_code,
            ),
            patient=patient_ref,
            occurrenceDateTime=_now_iso(),
            lotNumber=lot_no,
        )

        imm_json = immunization.json()
        parsed_imm = Immunization.parse_raw(imm_json)
        assert parsed_imm.dict() == immunization.dict(), f"Immunization round-trip failed at trial {trial}"

        # 4. Randomized DiagnosticReport
        diag_report = DiagnosticReport(
            id=f"diag-{trial}-{rnd.randint(1000, 9999)}",
            status="final",
            code=CodeableConcept(text="Diagnostic Laboratory Report"),
            subject=patient_ref,
            effectiveDateTime=_now_iso(),
            result=[Reference(reference=f"Observation/{observation.id}")],
            conclusion=f"Diagnostic outcome verified for trial {trial}",
        )

        diag_json = diag_report.json()
        parsed_diag = DiagnosticReport.parse_raw(diag_json)
        assert parsed_diag.dict() == diag_report.dict(), f"DiagnosticReport round-trip failed at trial {trial}"

        # 5. Randomized Encounter
        encounter = Encounter(
            id=f"enc-{trial}-{rnd.randint(1000, 9999)}",
            status=rnd.choice(["in-progress", "completed"]),
            class_fhir=[
                CodeableConcept(
                    coding=[
                        Coding(
                            system="http://terminology.hl7.org/CodeSystem/v3-ActCode",
                            code="AMB",
                            display="ambulatory",
                        )
                    ]
                )
            ],
            subject=patient_ref,
            actualPeriod={
                "start": _now_iso(),
            },
        )

        enc_json = encounter.json()
        parsed_enc = Encounter.parse_raw(enc_json)
        assert parsed_enc.dict() == encounter.dict(), f"Encounter round-trip failed at trial {trial}"

        # 6. Compound Document Bundle
        comp_id = f"comp-{trial}-{rnd.randint(1000, 9999)}"
        composition = Composition(
            id=comp_id,
            status="final",
            type=CodeableConcept(text="Comprehensive Assessment Note"),
            subject=[patient_ref],
            date=_now_iso(),
            author=[Reference(reference="Practitioner/asha-worker-01", display="ASHA Worker")],
            title=f"Record Bundle {trial}",
            section=[
                CompositionSection(
                    title="Clinical Entries",
                    entry=[
                        Reference(reference=f"Observation/{observation.id}"),
                        Reference(reference=f"Immunization/{immunization.id}"),
                        Reference(reference=f"DiagnosticReport/{diag_report.id}"),
                    ],
                )
            ],
        )

        bundle = Bundle(
            id=f"bundle-p17-{trial}",
            meta=Meta(
                profile=["https://nrces.in/ndhm/fhir/r4/StructureDefinition/WellnessRecord"],
            ),
            type="document",
            timestamp=_now_iso(),
            entry=[
                BundleEntry(fullUrl=f"Composition/{comp_id}", resource=composition),
                BundleEntry(fullUrl=f"Patient/{patient_id}", resource=patient),
                BundleEntry(fullUrl=f"Observation/{observation.id}", resource=observation),
                BundleEntry(fullUrl=f"Immunization/{immunization.id}", resource=immunization),
                BundleEntry(fullUrl=f"DiagnosticReport/{diag_report.id}", resource=diag_report),
                BundleEntry(fullUrl=f"Encounter/{encounter.id}", resource=encounter),
            ],
        )

        bundle_json = bundle.json()
        parsed_bundle = Bundle.parse_raw(bundle_json)

        # Invariant: deep dictionary equality with no lost, truncated, or coerced attributes
        assert parsed_bundle.dict() == bundle.dict(), (
            f"Compound Bundle round-trip failed at trial {trial}"
        )
        assert len(parsed_bundle.entry) == 6
