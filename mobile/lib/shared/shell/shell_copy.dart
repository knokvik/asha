/// Short labels for the four shell pages. English is the fallback.
String shellText(String code, String key) {
  final app =
      AppLocalizations.supportedLocales.any(
        (locale) => locale.languageCode == code,
      )
      ? lookupAppLocalizations(Locale(code))
      : lookupAppLocalizations(const Locale('en'));
  final localized = switch (key) {
    'drawerHome' || 'home' => app.home,
    'drawerDue' || 'dueTitle' => app.dueList,
    'drawerHomes' => app.households,
    'addHousehold' => app.registerHousehold,
    'triage' || 'drawerTriage' => app.triage,
    'drawerSettings' || 'settings' => app.settings,
    'learning' => app.learning,
    'earnings' => app.incentives,
    _ => null,
  };
  if (localized != null) return localized;
  final table = _copy[code] ?? _copy['en']!;
  return table[key] ?? _copy['en']![key] ?? key;
}

